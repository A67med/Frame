import type { FontPairId, ThemePreset } from "./theme";
import { DEFAULT_THEME_DESIGN, type ThemeDesign } from "./theme-design";

type CollectionId = "noir-cinema" | "aurora-frame" | "minimal-frost" | "editorial" | "retro-cinema";

function theme(
  id: CollectionId,
  name: string,
  blurb: string,
  palette: [string, string, string, string, string, string, string, string, string],
  fontPair: FontPairId,
  design: Partial<ThemeDesign>,
): ThemePreset {
  const [canvas, surface, elevated, raised, ink, muted, subtle, edge, accent] = palette;
  return {
    id,
    name,
    blurb,
    swatch: [canvas, surface, accent],
    layout: "frame",
    fontPair,
    cardStyle: "flat",
    buttonStyle: "flat",
    bokeh: false,
    design: { ...DEFAULT_THEME_DESIGN, ...design },
    tokens: {
      "--color-canvas": canvas,
      "--color-surface": surface,
      "--color-elevated": elevated,
      "--color-raised": raised,
      "--color-ink": ink,
      "--color-ink-muted": muted,
      "--color-ink-subtle": subtle,
      "--color-edge": `${edge}8c`,
      "--color-edge-soft": `${edge}40`,
      "--color-accent": accent,
      "--color-accent-soft": `${accent}2e`,
      "--color-danger": id === "minimal-frost" || id === "editorial" ? "#b4233c" : "#ff8694",
    },
  };
}

